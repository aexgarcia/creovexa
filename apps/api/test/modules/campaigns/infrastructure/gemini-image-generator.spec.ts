import { mkdtemp, rm } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join, resolve } from 'node:path';
import sharp from 'sharp';
import { readImageGenerationConfig } from '#app/config/image-generation.config';
import { MAX_IMAGE_BYTES } from '#app/infrastructure/image-files';
import {
  domainFixture,
  ORG,
  OTHER_ORG,
  CAMPAIGN,
  GENERATION,
  testId,
} from '../../../support/campaign-fakes.js';
import type { GenerateImageInput } from '#app/modules/campaigns/application/ports/image-generator';
import { LocalImageArtifacts } from '#app/modules/campaigns/infrastructure/local-image-artifacts';
import { GeminiImageGenerator } from '#app/modules/campaigns/infrastructure/gemini-image-generator';

describe('GeminiImageGenerator', () => {
  let directory: string;
  let artifacts: LocalImageArtifacts;
  let input: GenerateImageInput;
  let source: Buffer;
  let generated: Buffer;
  const config = { apiKey: 'test-image-secret', model: 'gemini-test-image', timeoutMs: 100 };
  const envelope = (bytes: Buffer, mimeType = 'image/png') => ({
    candidates: [
      {
        finishReason: 'STOP',
        content: { parts: [{ inlineData: { mimeType, data: bytes.toString('base64') } }] },
      },
    ],
  });

  beforeAll(async () => {
    directory = await mkdtemp(join(tmpdir(), 'creovexa-gemini-image-'));
    artifacts = new LocalImageArtifacts(directory);
    source = await sharp({ create: { width: 16, height: 16, channels: 3, background: '#125580' } })
      .png()
      .toBuffer();
    generated = await sharp(source).negate().png().toBuffer();
    const snapshot = domainFixture().snapshot.data;
    const scope = {
      organizationId: ORG,
      campaignId: CAMPAIGN,
      generationId: GENERATION,
      operationId: testId(804),
    };
    input = {
      ...scope,
      referenceImage: {
        reference: await artifacts.write(scope, source),
        contentType: 'image/png',
        width: 16,
        height: 16,
      },
      imagePrompt: 'Composición de producto con luz suave, sin textos.',
      copy: {
        headline: 'Descubre el producto',
        caption: 'Datos exactos de la campaña.',
        cta: snapshot.cta,
        hashtags: ['#Producto'],
      },
      snapshot,
    };
  });

  afterAll(async () => {
    if (directory && resolve(directory).startsWith(resolve(tmpdir()) + '\\creovexa-gemini-image-'))
      await rm(directory, { recursive: true });
    else if (
      directory &&
      resolve(directory).startsWith(resolve(tmpdir()) + '/creovexa-gemini-image-')
    )
      await rm(directory, { recursive: true });
  });

  function fixture(response?: Response, timeoutMs = 1000) {
    const http = vi
      .fn<typeof fetch>()
      .mockResolvedValue(response ?? Response.json(envelope(generated)));
    const logger = { log: vi.fn() };
    return {
      http,
      logger,
      adapter: new GeminiImageGenerator({ ...config, timeoutMs }, artifacts, http, logger),
    };
  }

  it('sends the exact photo and frozen context to a fixed endpoint and stages the generated bytes', async () => {
    const f = fixture();
    const result = await f.adapter.generate(input);
    expect(result).toMatchObject({ contentType: 'image/png', width: 16, height: 16 });
    expect(result.reference).not.toBe(input.referenceImage.reference);
    expect(await artifacts.read({ ...input, source: result })).toEqual(generated);
    const [url, options] = f.http.mock.calls[0]!;
    expect(url).toBe(
      'https://generativelanguage.googleapis.com/v1/models/gemini-test-image:generateContent',
    );
    expect(url).not.toContain(config.apiKey);
    expect(options!.redirect).toBe('error');
    expect(new Headers(options!.headers).get('x-goog-api-key')).toBe(config.apiKey);
    const body = JSON.parse(options!.body as string);
    expect(body.contents[0].parts[1].inlineData).toEqual({
      mimeType: 'image/png',
      data: source.toString('base64'),
    });
    expect(JSON.parse(body.contents[0].parts[0].text)).toEqual({
      imagePrompt: input.imagePrompt,
      copy: input.copy,
      snapshot: input.snapshot,
    });
    expect(body.generationConfig).toEqual({
      candidateCount: 1,
      responseModalities: ['TEXT', 'IMAGE'],
      responseFormat: { image: { aspectRatio: '1:1', imageSize: '1K' } },
    });
    expect(body.systemInstruction.parts[0].text).toContain('Preserve its identity');
    expect(body.systemInstruction.parts[0].text).toContain('Do not draw text');
    const logs = JSON.stringify(f.logger.log.mock.calls);
    expect(logs).not.toContain(config.apiKey);
    expect(logs).not.toContain(input.imagePrompt);
    expect(logs).not.toContain(source.toString('base64'));
    expect(logs).not.toContain(input.snapshot.product.description);
  });

  it('accepts explanatory text but ignores thought images', async () => {
    const f = fixture(
      Response.json({
        candidates: [
          {
            finishReason: 'STOP',
            content: {
              parts: [
                {
                  thought: true,
                  inlineData: { mimeType: 'image/png', data: source.toString('base64') },
                },
                { text: 'Private explanation, never logged or stored as copy.' },
                { inlineData: { mimeType: 'image/png', data: generated.toString('base64') } },
              ],
            },
          },
        ],
      }),
    );
    expect(await f.adapter.generate(input)).toHaveProperty('contentType', 'image/png');
    expect(JSON.stringify(f.logger.log.mock.calls)).not.toContain('Private explanation');
  });

  it.each(['SAFETY', 'IMAGE_SAFETY', 'PROHIBITED_CONTENT'])(
    'reports provider refusal %s without retry',
    async (reason) => {
      const f = fixture(Response.json({ candidates: [{ finishReason: reason }] }));
      await expect(f.adapter.generate(input)).rejects.toMatchObject({ code: 'REFUSED' });
      expect(f.http).toHaveBeenCalledTimes(1);
    },
  );

  it('reports prompt blocking without exposing provider text', async () => {
    const f = fixture(
      Response.json({ promptFeedback: { blockReason: 'SAFETY', blockReasonMessage: 'private' } }),
    );
    await expect(f.adapter.generate(input)).rejects.toMatchObject({ code: 'REFUSED' });
    expect(JSON.stringify(f.logger.log.mock.calls)).not.toContain('private');
  });

  it.each([
    {},
    { candidates: [] },
    { candidates: [null] },
    { candidates: [{ finishReason: 'MAX_TOKENS' }] },
    { candidates: [{ finishReason: 'STOP', content: { parts: [{ text: 'Only text' }] } }] },
    {
      candidates: [
        {
          finishReason: 'STOP',
          content: { parts: [{ fileData: { fileUri: 'http://127.0.0.1:9000/private' } }] },
        },
      ],
    },
    {
      candidates: [
        {
          finishReason: 'STOP',
          content: { parts: [{ inlineData: { mimeType: 'image/png', data: 'not-base64' } }] },
        },
      ],
    },
  ])('rejects incomplete or untrusted output %j', async (body) => {
    const f = fixture(Response.json(body));
    await expect(f.adapter.generate(input)).rejects.toMatchObject({ code: 'INVALID_OUTPUT' });
    expect(f.http).toHaveBeenCalledTimes(1);
  });

  it('rejects multiple generated images instead of choosing one', async () => {
    const body = envelope(generated);
    body.candidates[0]!.content.parts.push(body.candidates[0]!.content.parts[0]!);
    const f = fixture(Response.json(body));
    await expect(f.adapter.generate(input)).rejects.toMatchObject({ code: 'INVALID_OUTPUT' });
  });

  it.each(['html', 'truncated', 'mime', 'svg'])(
    'validates actual image bytes: %s',
    async (kind) => {
      const bytes =
        kind === 'html'
          ? Buffer.from('<html>bad</html>')
          : kind === 'truncated'
            ? generated.subarray(0, 33)
            : generated;
      const f = fixture(
        Response.json(
          envelope(
            bytes,
            kind === 'mime' ? 'image/jpeg' : kind === 'svg' ? 'image/svg+xml' : 'image/png',
          ),
        ),
      );
      await expect(f.adapter.generate(input)).rejects.toMatchObject({ code: 'INVALID_OUTPUT' });
      expect(f.http).toHaveBeenCalledTimes(1);
    },
  );

  it.each(['data:image/png;base64,AAAA', 'AAAA=', 'AB==', ''])(
    'rejects noncanonical base64 %j',
    async (data) => {
      const f = fixture(
        Response.json({
          candidates: [
            {
              finishReason: 'STOP',
              content: { parts: [{ inlineData: { mimeType: 'image/png', data } }] },
            },
          ],
        }),
      );
      await expect(f.adapter.generate(input)).rejects.toMatchObject({ code: 'INVALID_OUTPUT' });
    },
  );

  it('bounds declared response size before reading', async () => {
    const f = fixture(
      new Response('ignored', { headers: { 'content-length': String(MAX_IMAGE_BYTES * 2) } }),
    );
    await expect(f.adapter.generate(input)).rejects.toMatchObject({ code: 'INVALID_OUTPUT' });
  });

  it('bounds streamed response bytes even without Content-Length', async () => {
    const f = fixture(
      new Response(
        new ReadableStream({
          start(controller) {
            controller.enqueue(new Uint8Array(MAX_IMAGE_BYTES * 2));
            controller.close();
          },
        }),
      ),
    );
    await expect(f.adapter.generate(input)).rejects.toMatchObject({ code: 'INVALID_OUTPUT' });
  });

  it('rejects malformed JSON', async () => {
    const f = fixture(new Response('not JSON'));
    await expect(f.adapter.generate(input)).rejects.toMatchObject({ code: 'INVALID_OUTPUT' });
  });

  it.each([401, 403, 429, 503])(
    'does not retry or leak upstream errors for HTTP %s',
    async (status) => {
      const f = fixture(new Response('secret provider body', { status }));
      await expect(f.adapter.generate(input)).rejects.toMatchObject({
        code: status === 429 ? 'RATE_LIMITED' : 'UNAVAILABLE',
      });
      expect(f.http).toHaveBeenCalledTimes(1);
      expect(JSON.stringify(f.logger.log.mock.calls)).not.toContain('secret provider body');
    },
  );

  it('aborts a slow request without automatically charging for a retry', async () => {
    const f = fixture(undefined, 100);
    f.http.mockImplementation(
      (_url, options) =>
        new Promise((_resolve, reject) => {
          options!.signal!.addEventListener('abort', () => reject(options!.signal!.reason), {
            once: true,
          });
        }),
    );
    await expect(f.adapter.generate(input)).rejects.toMatchObject({ code: 'TIMEOUT' });
    expect(f.http).toHaveBeenCalledTimes(1);
  });

  it('bounds a stalled response body after successful headers', async () => {
    const cancel = vi.fn();
    const f = fixture(new Response(new ReadableStream({ cancel })), 100);
    await expect(f.adapter.generate(input)).rejects.toMatchObject({ code: 'TIMEOUT' });
    expect(f.http).toHaveBeenCalledTimes(1);
    expect(cancel).toHaveBeenCalled();
  });

  it('does not expose fetch errors or stage the original photo as fallback', async () => {
    const f = fixture();
    f.http.mockRejectedValue(new Error('secret provider URL and key'));
    await expect(f.adapter.generate(input)).rejects.toMatchObject({ code: 'UNAVAILABLE' });
    expect(f.http).toHaveBeenCalledTimes(1);
    expect(JSON.stringify(f.logger.log.mock.calls)).not.toContain('secret provider URL');
  });

  it.each(['organization', 'operation', 'path', 'metadata'])(
    'rejects an invalid source scope before networking: %s',
    async (kind) => {
      const f = fixture();
      const change =
        kind === 'organization'
          ? { organizationId: OTHER_ORG }
          : kind === 'operation'
            ? { operationId: testId(805) }
            : {
                referenceImage: {
                  ...input.referenceImage,
                  ...(kind === 'path' ? { reference: '../../.env' } : { width: 999 }),
                },
              };
      await expect(f.adapter.generate({ ...input, ...change })).rejects.toMatchObject({
        code: 'INVALID_OUTPUT',
      });
      expect(f.http).not.toHaveBeenCalled();
    },
  );

  it.each(['', 'x'.repeat(4001)])(
    'rejects invalid prompt length before networking',
    async (imagePrompt) => {
      const f = fixture();
      await expect(f.adapter.generate({ ...input, imagePrompt })).rejects.toMatchObject({
        code: 'INVALID_OUTPUT',
      });
      expect(f.http).not.toHaveBeenCalled();
    },
  );

  it('keeps calls disabled when only the free copy configuration is present', async () => {
    const selected = readImageGenerationConfig({
      GEMINI_API_KEY: config.apiKey,
      GEMINI_COPY_MODEL: 'gemini-copy',
    });
    const f = fixture();
    const adapter = new GeminiImageGenerator(
      selected.provider === 'gemini' ? selected.settings : null,
      artifacts,
      f.http,
    );
    await expect(adapter.generate(input)).rejects.toMatchObject({ code: 'UNAVAILABLE' });
    expect(f.http).not.toHaveBeenCalled();
  });

  it('makes no request with an explicitly selected provider but missing key', async () => {
    const f = fixture();
    await expect(
      new GeminiImageGenerator({ ...config, apiKey: null }, artifacts, f.http).generate(input),
    ).rejects.toMatchObject({ code: 'UNAVAILABLE' });
    expect(f.http).not.toHaveBeenCalled();
  });
});
